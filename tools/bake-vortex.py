WIDTH, HEIGHT, SAMPLES = 164, 26, 12


def polygons(outline):
    tokens = iter(outline.split())

    def point():
        return float(next(tokens)), float(next(tokens))

    for command in tokens:
        if command == 'M':
            contour = [point()]
        elif command == 'L':
            contour.append(point())
        elif command == 'Q':
            a, b, c = contour[-1], point(), point()
            for i in range(1, 17):
                t = i / 16
                contour.append(tuple((1-t)**2*p + 2*(1-t)*t*q + t*t*r
                                     for p, q, r in zip(a, b, c)))
        elif command == 'Z':
            yield contour + [contour[0]]
        else:
            raise ValueError(command)


def bake():
    coverage = [[0] * WIDTH for _ in range(HEIGHT)]
    for outline in OUTLINES:
        edges = [(a, b) for poly in polygons(outline) for a, b in zip(poly, poly[1:])]
        for sy in range(HEIGHT * SAMPLES):
            y = (sy + 0.5) / SAMPLES
            hits = sorted(ax + (bx-ax)*(y-ay)/(by-ay)
                          for (ax, ay), (bx, by) in edges if min(ay, by) <= y < max(ay, by))
            for left, right in zip(hits[::2], hits[1::2]):
                for sx in range(ceil(left*SAMPLES - 0.5), ceil(right*SAMPLES - 0.5)):
                    coverage[sy // SAMPLES][sx // SAMPLES] += 1
    ramp = '0123456789abcdefg'
    return [''.join(ramp[min(16, round(16 * n / SAMPLES**2))] for n in row) for row in coverage]


if __name__ == '__main__':
    out = Path(__file__).resolve().parents[1] / 'src/ui/vortex_coverage.h'
    rows = '\n'.join(f'    "{row}",' for row in bake())
    out.write_text('// Generated by tools/bake-vortex.py from the native lettering outlines.\n#pragma once\n'
                   'namespace cortex::wordmark {\ninline constexpr char coverage[][165] = {\n'
                   + rows + '\n};\n}\n')
